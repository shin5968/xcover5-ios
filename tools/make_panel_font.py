order=['.notdef']+['g'+str(ord(c)) for c in sorted(patterns)]
glyphs={};metrics={}
for name,pattern in [('.notdef','11111/10001/10101/10101/10101/10001/11111')]+[(('g'+str(ord(c))),patterns[c]) for c in sorted(patterns)]:
 pen=TTGlyphPen(None)
 for y,row in enumerate(pattern.split('/')):
  for x,bit in enumerate(row):
   if bit=='1':
    a,b=x*100,(6-y)*100
    pen.moveTo((a,b));pen.lineTo((a,b+100));pen.lineTo((a+100,b+100));pen.lineTo((a+100,b));pen.closePath()
 glyphs[name]=pen.glyph();metrics[name]=(600,0)
f=FontBuilder(1000,isTTF=True);f.setupGlyphOrder(order)
f.setupCharacterMap({ord(c):'g'+str(ord(c)) for c in patterns})
f.setupGlyf(glyphs);f.setupHorizontalMetrics(metrics);f.setupHorizontalHeader(ascent=800,descent=-200)
f.setupNameTable({'familyName':'XCover Panel Test','styleName':'Regular','uniqueFontIdentifier':'XCoverPanelTest1','fullName':'XCover Panel Test Regular','psName':'XCoverPanelTest-Regular','version':'Version 1.0'})
